const H = "module m @ 0.1\n";
const H4 = "mandate @ 0.4\n\nmodule m @ 0.1\n";
const H3 = "mandate @ 0.3\n\nmodule m @ 0.1\n";
/** An expression as the value of a constant. */
const e = (expr: string): string => `${H}let x = ${expr}\n`;
/** Statements as the body of a function. */
const f = (body: string): string => `${H}fn f() -> Int {\n${body}\n}\n`;
/** A statement, indented, as the body of a function. */
const st = (stmt: string): string => f(`  ${stmt}`);
/** Statements as the body of a test. */
const t = (body: string): string => `${H}test "t" {\n${body}\n}\n`;

