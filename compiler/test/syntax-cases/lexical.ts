const H = "module m @ 0.1\n";
const x = (e: string): string => `${H}let x = ${e}\n`;

/** Every reserved word (the parser's `RESERVED`, which the test holds this list to). */
export const RESERVED_WORDS = [
  "module", "use", "type", "enum", "capability", "fn", "pub", "extern", "effect", "agent", "skill",
  "workflow", "contract", "let", "par", "delegate", "spawn", "await", "verify", "infer",
  "if", "else", "loop", "return", "switch", "on", "with", "in", "where", "and", "or", "not",
  "true", "false",
];

/** The reserved words that start an expression, and three that do not. */
const STARTS_AN_EXPRESSION = ["not", "true", "false", "delegate", "spawn", "await", "verify", "infer", "effect", "switch", "in", "if", "fn"];

/** Each reserved word as a definition's name, and some where an expression starts. */
export const reservedWords: Array<[string, string]> = RESERVED_WORDS.flatMap((w): Array<[string, string]> => [
  [`'${w}' as a definition name`, `${H}let ${w} = 1\n`],
  ...(STARTS_AN_EXPRESSION.includes(w) ? [[`'${w}' where an expression starts`, `${H}let x = ${w}\n`] as [string, string]] : []),
]);

