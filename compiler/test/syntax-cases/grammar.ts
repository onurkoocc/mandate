// Inputs about the grammar: every kind of definition, statement and
// expression, each in its smallest form and with every optional part.
// Each is `[name, input]`. No imports (see lexical.ts).

const H = "module m @ 0.1\n";
const h = (language: string): string => `mandate @ ${language}\n\nmodule m @ 0.1\n`;
/** A definition after the header. */
const d = (body: string): string => `${H}${body}\n`;
/** A definition after a 0.2 header, and a 0.4 header. */
const d2 = (body: string): string => `${h("0.2")}${body}\n`;
const d4 = (body: string): string => `${h("0.4")}${body}\n`;
/** A function body after the header. */
const f = (body: string): string => `${H}fn f() -> Int {\n${body}\n}\n`;
/** An expression as the value of a constant. */
const e = (expr: string): string => `${H}let x = ${expr}\n`;
/** An expression as a statement of a function. */
const st = (stmt: string): string => f(`  ${stmt}`);

